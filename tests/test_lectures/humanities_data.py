def correct_answers_payload(lec: HumanitiesLecture) -> list[dict]:
    """全問正解の回答(本文の answers)。"""
    return [
        {"question_index": i, "selected_answer": q.correct_text, "is_correct": 1}
        for i, q in enumerate(lec.questions, 1)
    ]
