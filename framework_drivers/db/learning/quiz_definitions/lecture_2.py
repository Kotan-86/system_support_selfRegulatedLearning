"""lecture-2（モンティ・ホール問題）の小テスト定義。"""
from __future__ import annotations

from domain.learning.quiz_definition import Question, QuizDefinition

QUIZ_TITLE = "モンティ・ホール問題：直感と論理のクイズ"
QUIZ_DESCRIPTION = (
    "モンティ・ホール問題の論理展開を理解できているかの確認クイズです。"
)


def build_quiz_definition() -> QuizDefinition:
    """lecture-2 の QuizDefinition を構築する。"""
    return QuizDefinition(
    questions=(
        Question(
            index=1,
            text=(
                "標準的なモンティ・ホール問題で、司会者がハズレの扉を1つ開けた後、"
                "ある学習者は「扉が2つ残ったので、当たりの確率はどちらも1/2だ」"
                "と考えました。この考えの修正として最も適切なものはどれですか？"
            ),
            choices=(
                "扉が2つ残れば、必ずそれぞれ1/2になる",
                "司会者は当たりを知ったうえでハズレを開けているため、最初の扉は1/3、もう一方は2/3のままである",
                "司会者が扉を開けると、最初に選んだ扉の確率が2/3に上がる",
                "扉を開けた後の確率は計算できない",
            ),
            correct_answer=(
                "司会者は当たりを知ったうえでハズレを開けているため、最初の扉は1/3、もう一方は2/3のままである"
            ),
        ),
        Question(
            index=2,
            text=(
                "「扉を変えると当たる確率が2/3になる」という結論を成り立たせるために、"
                "必要な司会者の行動ルールはどれですか？"
            ),
            choices=(
                "司会者は当たりを知らず、残った扉からランダムに1つ開ける",
                "司会者は、挑戦者が当たりを選んだときだけ扉を変える機会を与える",
                "司会者は当たりを知っており、選ばれていないハズレの扉を必ず開け、毎回変更の機会を与える",
                "司会者は、挑戦者が最初に選んだ扉も含めてランダムに開ける",
            ),
            correct_answer=(
                "司会者は当たりを知っており、選ばれていないハズレの扉を必ず開け、毎回変更の機会を与える"
            ),
        ),
        Question(
            index=3,
            text=(
                "司会者が当たりの場所を知らず、選ばれていない扉からランダムに1つ開けたところ、"
                "たまたまハズレだったとします。この場合、残った2つの扉の当たる確率は"
                "どうなりますか？"
            ),
            choices=(
                "最初に選んだ扉が1/3、もう一方の扉が2/3になる",
                "最初に選んだ扉が2/3、もう一方の扉が1/3になる",
                "どちらの扉も1/2になる",
                "司会者がランダムに開けたので、どちらの確率も1/3のままになる",
            ),
            correct_answer=(
                "どちらの扉も1/2になる"
            ),
        ),
        Question(
            index=4,
            text=(
                "扉が100枚あり、当たりが1枚だけある場合を考えます。挑戦者が1枚を選んだ後、"
                "当たりを知っている司会者が、選ばれていない98枚のハズレを開けました。"
                "残った1枚へ変更した場合に当たる確率はどれですか？"
            ),
            choices=(
                "1/100",
                "1/2",
                "98/100",
                "99/100",
            ),
            correct_answer=(
                "99/100"
            ),
        ),
        Question(
            index=5,
            text=(
                "3枚の扉を「当たり・ハズレA・ハズレB」とし、最初に選ぶ3つのパターンを"
                "すべて考えます。司会者が必ずハズレを開けた後、毎回扉を変えると、"
                "3つのパターンの結果はどうなりますか？"
            ),
            choices=(
                "当たりを選んだ場合だけ勝ち、ハズレA・ハズレBを選んだ場合は負けるため、勝率は1/3",
                "当たりを選んだ場合は負け、ハズレA・ハズレBを選んだ場合は勝つため、勝率は2/3",
                "どの扉を選んでも結果は半々になるため、勝率は1/2",
                "司会者が必ずハズレを開けるため、どの扉から変更しても必ず勝つ",
            ),
            correct_answer=(
                "当たりを選んだ場合は負け、ハズレA・ハズレBを選んだ場合は勝つため、勝率は2/3"
            ),
        ),
    )
)
