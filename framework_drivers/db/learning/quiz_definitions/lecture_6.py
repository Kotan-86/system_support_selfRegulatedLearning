"""lecture-6 の小テスト定義（付録A のとおり。解説は持たない）。"""
from __future__ import annotations

from domain.learning.quiz_definition import Question, QuizDefinition

QUIZ_TITLE = "言語の仕組み（音声・音韻・語）"
QUIZ_DESCRIPTION = "動画で解説された言語の仕組み（音声・音韻・語）に関する確認問題です。"


def build_quiz_definition() -> QuizDefinition:
    """lecture-6 の QuizDefinition を構築する。"""
    return QuizDefinition(
        questions=(
            Question(
                index=1,
                text="動画では、言語を一言でどのように説明していましたか。",
                choices=(
                    "気持ちを表す声の集まり",
                    "記号の体系",
                    "文字の書き方の決まり",
                    "ものの形を写した絵の集まり",
                ),
                correct_answer="記号の体系",
            ),
            Question(
                index=2,
                text="動画では「猫をカバと呼んでもよかった」と説明していました。この説明に最も近いものはどれですか。",
                choices=(
                    "猫とカバは、言葉の上では同じ動物である。",
                    "呼び名は、一人ひとりが自由に変えても相手に伝わる。",
                    "動物の姿が分かれば、その呼び名も自然に分かる。",
                    "呼び名が「猫」でなければならない理由はなく、約束によって結びついている。",
                ),
                correct_answer="呼び名が「猫」でなければならない理由はなく、約束によって結びついている。",
            ),
            Question(
                index=3,
                text="言語の特徴である「線条性」とは、どのようなことでしょうか。",
                choices=(
                    "音を、時間の流れに沿って順に並べること。",
                    "一つの単語に含まれる音を、すべて同時に出すこと。",
                    "同じ音を使えば、順番を変えても意味が変わらないこと。",
                    "話した内容を、必ず横一列の文字で書き表せること。",
                ),
                correct_answer="音を、時間の流れに沿って順に並べること。",
            ),
            Question(
                index=4,
                text="動画では「僕はたぬきです」という文を使って、二重分節を説明していました。その分け方に合うものはどれですか。",
                choices=(
                    "文を前半と後半に分け、それぞれの意味を考える。",
                    "文を文字に分け、さらに文字を線に分ける。",
                    "文を「僕／は／たぬき／です」のように語に分け、さらに語を音に分ける。",
                    "文を語に分け、それぞれの語を別の言語に訳す。",
                ),
                correct_answer="文を「僕／は／たぬき／です」のように語に分け、さらに語を音に分ける。",
            ),
            Question(
                index=5,
                text="「さる」と「まる」では、最初の子音が /s/ から /m/ に変わると、別の意味の語になります。この例から分かることはどれですか。",
                choices=(
                    "/s/ という音だけで、「猿」という動物を表している。",
                    "音そのものに意味がなくても、語の意味を区別する働きがある。",
                    "/m/ という音には、どの語でも「丸い」という意味がある。",
                    "一つの音を変えても、語全体の意味は変わらない。",
                ),
                correct_answer="音そのものに意味がなくても、語の意味を区別する働きがある。",
            ),
        ),
    )
